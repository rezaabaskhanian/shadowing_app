import { QueryClient } from '@tanstack/react-query';

/**
 * کلاینت مشترک react-query برای کل اپ.
 *
 * تا پیش از این، کش و بی‌اعتبارسازی دستی نوشته شده بود (یک Map داخل
 * ScenesContext به‌علاوه‌ی یک reload() که باید یادمان می‌ماند صدایش بزنیم).
 * آن کش سیاست انقضا نداشت، درخواست‌های هم‌زمان را ادغام نمی‌کرد و بی‌اعتبار
 * کردنش دستی بود.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // داده‌ی صحنه‌ها کم عوض می‌شود؛ پنج دقیقه تازه حساب می‌شود تا هر بار
      // برگشتن به صفحه‌ی خانه یک درخواست شبکه نزند.
      staleTime: 5 * 60 * 1000,
      // روی موبایل قطعی کوتاه شبکه عادی است، ولی تلاش بی‌پایان هم باتری و
      // داده می‌سوزاند.
      retry: 2,
    },
  },
});
